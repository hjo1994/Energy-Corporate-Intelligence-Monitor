"""RawToBronze DAG: waits for the source Excel to appear/change and loads
each of its four raw sheets 1:1 into its extract (bronze) table.

One load task per entry in sources.SOURCES. Each task emits the Asset of its
extract table, which schedules the matching DAG generated by the
BronzeToSilver meta DAG (dags/bronze_to_silver_dag.py).
"""
from __future__ import annotations

import datetime
import os
from pathlib import Path

from airflow.sdk import DAG, Asset, task

from ai_cockpit_ingestion import config
from ai_cockpit_ingestion.operators.raw_to_bronze import RawToBronzeOperator
from ai_cockpit_ingestion.operators.source_file_sensor import MARKER_NAME, SourceFileSensor
from ai_cockpit_ingestion.sources import SOURCES

SENSOR_TASK_ID = "wait_for_source_file"

with DAG(
    dag_id="raw_to_bronze",
    schedule="@hourly",
    start_date=datetime.datetime(2026, 1, 1),
    catchup=False,
    max_active_runs=1,
    tags=["ai-cockpit", "input-orchestration", "bronze"],
) as dag:

    wait_for_source_file = SourceFileSensor(
        task_id=SENSOR_TASK_ID,
        source_dir=str(config.SOURCE_DIR),
        filename_glob=config.SOURCE_FILENAME_GLOB,
        poke_interval=60,
        timeout=60 * 60 * 6,
        mode="reschedule",  # frees the worker slot between pokes
    )

    @task
    def mark_source_processed(ti=None) -> None:
        """Only after all four extracts loaded: remember the file's mtime, so
        the sensor skips it until it changes again.
        """
        source_file_path = ti.xcom_pull(task_ids=SENSOR_TASK_ID, key="source_file_path")
        source_file_mtime = ti.xcom_pull(task_ids=SENSOR_TASK_ID, key="source_file_mtime")
        marker = Path(source_file_path).parent / MARKER_NAME
        marker.touch()
        os.utime(marker, (source_file_mtime, source_file_mtime))

    loads = [
        RawToBronzeOperator(
            task_id=f"load_{source.key}",
            source_key=source.key,
            db_path=str(config.DB_PATH),
            sensor_task_id=SENSOR_TASK_ID,
            outlets=[Asset(name=source.extract_table, uri=source.asset_uri)],
        )
        for source in SOURCES
    ]

    wait_for_source_file >> loads >> mark_source_processed()
